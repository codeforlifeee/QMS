/* QMS service worker — minimal. Handles manual notification display and
 * click routing. We intentionally do NOT subscribe to a push server here;
 * notification creation is driven by the in-page poller in notification-
 * push.ts calling registration.showNotification(...). This gives us OS-
 * level banners without requiring VAPID keys or server push.
 */

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || '/';
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (client.url.endsWith(url) && 'focus' in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow(url);
    })
  );
});
